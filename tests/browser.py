    expect(page.get_by_text('Fault triggered',exact=True)).to_be_visible()
    page.get_by_label('Machine temperature (°C)',exact=True).fill('80')
    expect(page.get_by_role('status')).to_contain_text('NORMAL')
    expect(page.get_by_text('8 combinations tested',exact=False)).to_be_visible()
    page.get_by_label('Simulation interval (ms)').fill('250')
    page.get_by_role('button',name='Start simulation',exact=True).click()
    expect(page.get_by_text('Vibration crossed above threshold',exact=True)).to_be_visible(timeout=5000)
    page.get_by_role('button',name='Pause simulation',exact=True).click()
    print('PASS machine injections, strict boundaries, history, equivalence')
    page.get_by_role('button',name='Smart home',exact=True).click()
    expect(page.locator('.device.active')).to_have_count(0)
    page.screenshot(path='tests/home-desktop.png',full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    for module in ['Task planner','Course eligibility','Smart home','Scholarship','Fault detection']:
        page.get_by_role('button',name=module,exact=True).click()
        page.wait_for_timeout(200)
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), module+' overflows mobile viewport'
        page.get_by_role('button',name='Start demo',exact=True).click()
        expect(page.get_by_text('Step 1/3:',exact=False)).to_be_visible()
        page.get_by_role('button',name='Next demo step').click()
        expect(page.get_by_text('Step 2/3:',exact=False)).to_be_visible()
        page.get_by_role('button',name='Close demo').click()
    page.screenshot(path='tests/mobile.png',full_page=True)
    assert not errors, errors
    print('PASS tab-state retention, five mobile layouts, no runtime errors')
    browser.close()

