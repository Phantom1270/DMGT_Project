    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={"width":1440,"height":1000})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto('http://127.0.0.1:5180')
    page.wait_for_load_state('networkidle')
    expect(page.get_by_role('heading',name='Task dependency analysis')).to_be_visible()
    expect(page.locator('.react-flow__edge')).to_have_count(4)
    page.get_by_role('button',name='Start what-if',exact=True).click()
    page.get_by_label('Duration (units)').fill('3')
    expect(page.locator('.comparison')).to_contain_text('4 → 6')
    page.get_by_role('button',name='Discard scenario').click()
    expect(page.get_by_label('Duration (units)')).to_have_value('1')
    page.get_by_role('button',name='Next step',exact=True).click()
    expect(page.get_by_text('Processed: Design database',exact=True)).to_be_visible()
    page.get_by_role('button',name='Previous step',exact=True).click()
    page.get_by_label('Select item',exact=True).select_option('t4')
    page.get_by_role('group',name='Prerequisites').get_by_label('Design database',exact=True).check()
    expect(page.locator('.react-flow__edge')).to_have_count(4)
    page.get_by_role('button',name='Direct dependencies',exact=True).click()
    expect(page.locator('.react-flow__edge')).to_have_count(5)
    page.get_by_role('button',name='Hasse diagram',exact=True).click()
    expect(page.locator('.react-flow__edge')).to_have_count(4)
    page.get_by_role('button',name='Load cycle example').click()
    expect(page.get_by_role('alert')).to_contain_text('Cycle:')
    expect(page.get_by_role('button',name='Next step',exact=True)).to_be_disabled()
    page.get_by_role('button',name='Reset example',exact=True).click()
    page.get_by_label('New item name').fill('Write documentation')
    page.get_by_role('button',name='Add item',exact=True).click()
    expect(page.get_by_label('Name',exact=True)).to_have_value('Write documentation')
    page.get_by_role('button',name='Delete selected item').click()
    page.get_by_role('button',name='Undo',exact=True).click()
    expect(page.locator('.react-flow__node')).to_have_count(6)
    print('PASS task edits, undo, cycles, critical-path what-if, walkthrough')
    page.get_by_role('button',name='Course eligibility',exact=True).click()
    page.get_by_label('Programming',exact=True).last.check()
    page.get_by_label('Data Structures',exact=True).last.check()
    page.get_by_label('Discrete Mathematics',exact=True).last.check()
    expect(page.get_by_text('Eligible now: Algorithms.',exact=True)).to_be_visible()
    page.get_by_role('button',name='Start what-if completion').click()
    page.get_by_label('Algorithms',exact=True).last.check()
    expect(page.get_by_text('Eligible now: Machine Learning.',exact=True)).to_be_visible()
    page.get_by_role('button',name='Discard completions').click()
    expect(page.get_by_label('Algorithms',exact=True).last).not_to_be_checked()
    print('PASS course eligibility and temporary completions')
    page.get_by_role('button',name='Smart home',exact=True).click()
    page.get_by_role('button',name='Empty daytime',exact=True).click()
    expect(page.locator('.device.active')).to_have_count(0)
    page.get_by_role('button',name='Manual override',exact=True).click()
    expect(page.locator('.device.active')).to_have_count(1)
    page.get_by_role('button',name='Explain Light',exact=True).click()
    expect(page.get_by_text('OR gate:',exact=False)).to_be_visible()
    page.get_by_text('Explore truth table (8 combinations)',exact=True).click()
    page.get_by_role('button',name='Apply row 1',exact=True).click()
    expect(page.locator('.device.active')).to_have_count(0)
    print('PASS home presets, gate explanation, truth-row application')
    page.get_by_role('button',name='Scholarship',exact=True).click()
    expect(page.get_by_role('status')).to_contain_text('Not eligible')
    page.get_by_role('button',name='CGPA at threshold',exact=True).click()
    expect(page.get_by_role('status')).to_contain_text('Eligible under')
    page.get_by_role('button',name='Compare applicant',exact=True).click()
    page.get_by_label('Attendance (%)',exact=True).fill('74')
    expect(page.get_by_role('status')).to_contain_text('Not eligible')
    page.get_by_role('button',name='Discard applicant',exact=True).click()
    expect(page.get_by_label('Attendance (%)',exact=True)).to_have_value('75')
    page.get_by_label('Annual family income (₹)',exact=True).fill('-1')
